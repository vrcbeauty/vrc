const CART_KEY = "vrcBeautyCart";
const EXPIRY_KEY = "vrcBeautyCartExpiry";
const CART_DURATION = 12 * 60 * 60 * 1000;
let cart = JSON.parse(localStorage.getItem(CART_KEY) || "[]");
let expiry = Number(localStorage.getItem(EXPIRY_KEY) || 0);

const grid = document.getElementById("productGrid");
const cartDrawer = document.getElementById("cartDrawer");
const overlay = document.getElementById("overlay");
const cartItems = document.getElementById("cartItems");
const cartCount = document.getElementById("cartCount");
const cartTotal = document.getElementById("cartTotal");
const cartEmpty = document.getElementById("cartEmpty");
const cartTimer = document.getElementById("cartTimer");
const toast = document.getElementById("toast");

function money(n) {
  return "₦" + Number(n).toLocaleString("en-NG");
}

function saveCart() {
  localStorage.setItem(CART_KEY, JSON.stringify(cart));
  if (cart.length && !expiry) {
    expiry = Date.now() + CART_DURATION;
    localStorage.setItem(EXPIRY_KEY, String(expiry));
  }
  if (!cart.length) {
    expiry = 0;
    localStorage.removeItem(EXPIRY_KEY);
  }
}

function renderProducts(list = PRODUCTS) {
  grid.innerHTML = list.map(p => `
    <article class="product-card">
      <img class="product-image" src="${p.image}" alt="${escapeHtml(p.name)}" loading="lazy"
           onerror="this.style.objectFit='contain'; this.alt='Image not uploaded: ${p.image}';">
      <div class="product-body">
        <span class="product-number">PRODUCT ${String(p.id).padStart(2,"0")}</span>
        <h3 class="product-name">${escapeHtml(p.name)}</h3>
        <div class="product-price">${money(p.price)}</div>
        <button class="add-button" data-id="${p.id}">
          Add to Cart
        </button>
      </div>
    </article>
  `).join("");
}

function renderCart() {
  const totalQty = cart.reduce((sum, x) => sum + x.qty, 0);
  cartCount.textContent = totalQty;

  if (!cart.length) {
    cartItems.innerHTML = "";
    cartItems.style.display = "none";
    cartEmpty.style.display = "block";
    cartTotal.textContent = money(0);
    return;
  }

  cartItems.style.display = "block";
  cartEmpty.style.display = "none";

  cartItems.innerHTML = cart.map(item => `
    <div class="cart-row">
      <img src="${item.image}" alt="${escapeHtml(item.name)}"
           onerror="this.style.objectFit='contain';">
      <div>
        <p class="cart-name">${escapeHtml(item.name)}</p>
        <div class="cart-price">${money(item.price)} each</div>
        <div class="qty-controls">
          <button class="qty-btn" data-action="minus" data-id="${item.id}">−</button>
          <strong>${item.qty}</strong>
          <button class="qty-btn" data-action="plus" data-id="${item.id}">+</button>
        </div>
      </div>
      <button class="remove-btn" title="Remove item" aria-label="Remove ${escapeHtml(item.name)}"
              data-action="remove" data-id="${item.id}">🗑</button>
    </div>
  `).join("");

  const total = cart.reduce((sum, x) => sum + x.price * x.qty, 0);
  cartTotal.textContent = money(total);
}

function addToCart(id) {
  const product = PRODUCTS.find(p => p.id === id);
  if (!product) return;
  const existing = cart.find(x => x.id === id);

  if (existing) existing.qty += 1;
  else cart.push({...product, qty: 1});

  if (!expiry) {
    expiry = Date.now() + CART_DURATION;
    localStorage.setItem(EXPIRY_KEY, String(expiry));
  }
  saveCart();
  renderCart();
  showToast(`${product.name} added to cart`);
}

function updateQty(id, delta) {
  const item = cart.find(x => x.id === id);
  if (!item) return;
  item.qty += delta;
  if (item.qty <= 0) cart = cart.filter(x => x.id !== id);
  saveCart();
  renderCart();
}

function removeItem(id) {
  cart = cart.filter(x => x.id !== id);
  saveCart();
  renderCart();
}

function openCart() {
  cartDrawer.classList.add("open");
  overlay.classList.add("show");
  document.body.style.overflow = "hidden";
}

function closeCart() {
  cartDrawer.classList.remove("open");
  overlay.classList.remove("show");
  document.body.style.overflow = "";
}

function clearCart() {
  cart = [];
  saveCart();
  renderCart();
  showToast("Cart cleared");
}

function updateTimer() {
  if (!cart.length || !expiry) {
    cartTimer.textContent = "Cart expires in 12:00:00";
    return;
  }
  const remaining = expiry - Date.now();
  if (remaining <= 0) {
    cart = [];
    saveCart();
    renderCart();
    cartTimer.textContent = "Cart expired";
    showToast("Your 12-hour cart has expired");
    return;
  }
  const h = Math.floor(remaining / 3600000);
  const m = Math.floor((remaining % 3600000) / 60000);
  const s = Math.floor((remaining % 60000) / 1000);
  cartTimer.textContent = `Cart expires in ${String(h).padStart(2,"0")}:${String(m).padStart(2,"0")}:${String(s).padStart(2,"0")}`;
}

function checkout() {
  if (!cart.length) {
    showToast("Your cart is empty");
    return;
  }
  const lines = cart.map(x => `• ${x.name} x${x.qty} — ${money(x.price * x.qty)}`).join("\n");
  const total = cart.reduce((sum, x) => sum + x.price * x.qty, 0);
  const message = `Hello VRC BEAUTY, I would like to place an order.\n\n${lines}\n\nTotal: ${money(total)}`;
  const url = "https://wa.me/2348145935394?text=" + encodeURIComponent(message);
  window.open(url, "_blank");
}

function showToast(message) {
  toast.textContent = message;
  toast.classList.add("show");
  clearTimeout(window.toastTimer);
  window.toastTimer = setTimeout(() => toast.classList.remove("show"), 2200);
}

function escapeHtml(value) {
  return String(value).replace(/[&<>"']/g, ch => ({"&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;","'":"&#039;"}[ch]));
}

grid.addEventListener("click", e => {
  const button = e.target.closest(".add-button");
  if (!button) return;
  addToCart(Number(button.dataset.id));
  button.textContent = "Added ✓";
  button.classList.add("added");
  setTimeout(() => {
    button.textContent = "Add to Cart";
    button.classList.remove("added");
  }, 900);
});

cartItems.addEventListener("click", e => {
  const button = e.target.closest("[data-action]");
  if (!button) return;
  const id = Number(button.dataset.id);
  const action = button.dataset.action;
  if (action === "plus") updateQty(id, 1);
  if (action === "minus") updateQty(id, -1);
  if (action === "remove") removeItem(id);
});

document.getElementById("openCart").addEventListener("click", openCart);
document.getElementById("closeCart").addEventListener("click", closeCart);
overlay.addEventListener("click", closeCart);
document.getElementById("clearCart").addEventListener("click", clearCart);
document.getElementById("checkoutButton").addEventListener("click", checkout);

document.getElementById("searchInput").addEventListener("input", e => {
  const q = e.target.value.trim().toLowerCase();
  renderProducts(PRODUCTS.filter(p => p.name.toLowerCase().includes(q)));
});

renderProducts();
renderCart();
updateTimer();
setInterval(updateTimer, 1000);
